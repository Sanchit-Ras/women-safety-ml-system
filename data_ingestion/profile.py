"""Profile every raw file and write ``data/PROFILE.md``.

Run with ``python -m data_ingestion.profile``. The point is to *measure* the
facts every later design decision rests on (unit of analysis, schema eras,
name overlap) rather than assume them. The output doubles as the "before"
numbers for the README.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from data_ingestion.normalize import norm, norm_state

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "data" / "PROFILE.md"

ERA_A = RAW / "crimes_against_women_2001-2014.csv"
ERA_B = RAW / "districtwise-crime-against-women-2016.csv"
ERA_C = RAW / "districtwise-crime-against-women-2017-onwards.csv"
GEO = RAW / "india_district.geojson"

ERA_A_CATEGORIES = [
    "Rape",
    "Kidnapping and Abduction",
    "Dowry Deaths",
    "Assault on women with intent to outrage her modesty",
    "Insult to modesty of Women",
    "Cruelty by Husband or his Relatives",
    "Importation of Girls",
]
KEY_COLS_BC = {"id", "year", "state_name", "state_code", "district_name", "district_code", "registration_circles"}


def load_era_a() -> pd.DataFrame:
    df = pd.read_csv(ERA_A)
    df["state_n"] = df["STATE/UT"].map(norm_state)
    df["unit_n"] = df["DISTRICT"].map(norm)
    df["is_total"] = df["unit_n"].str.contains("total")
    df["total"] = df[ERA_A_CATEGORIES].sum(axis=1)
    return df


def category_cols(df: pd.DataFrame) -> list[str]:
    return [c for c in df.columns if c not in KEY_COLS_BC and not c.endswith("_n") and c != "total"]


def load_era_bc(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df["state_n"] = df["state_name"].map(norm_state)
    df["district_n"] = df["district_name"].map(norm)
    df["circle_n"] = df["registration_circles"].map(norm)
    df["total"] = df[category_cols(df)].sum(axis=1)
    return df


def load_geo() -> pd.DataFrame:
    with open(GEO, encoding="utf-8") as fh:
        feats = json.load(fh)["features"]
    geo = pd.DataFrame([{"state": f["properties"]["NAME_1"], "district": f["properties"]["NAME_2"]} for f in feats])
    geo["state_n"] = geo["state"].map(norm_state)
    geo["district_n"] = geo["district"].map(norm)
    return geo


def md_table(rows: list[tuple], header: tuple) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def coverage(src: set, dst: set) -> str:
    hit = len(src & dst)
    return f"{hit} / {len(src)} ({100 * hit / len(src):.1f}%)"


def main() -> None:
    a, b, c, geo = load_era_a(), load_era_bc(ERA_B), load_era_bc(ERA_C), load_geo()
    a_units = a[~a["is_total"]]
    lines: list[str] = ["# Raw data profile", "", "Generated by `python -m data_ingestion.profile`.", ""]

    # ---- per-era summary -------------------------------------------------
    lines += ["## Per-era summary", ""]
    lines.append(md_table([
        ("A 2001-2014", len(a), f"{a['Year'].min()}-{a['Year'].max()}", len(ERA_A_CATEGORIES),
         a_units["state_n"].nunique(), a_units.groupby(["state_n", "unit_n"]).ngroups, int(a["is_total"].sum())),
        ("B 2016", len(b), "2016", len(category_cols(b)), b["state_n"].nunique(),
         b.groupby(["state_n", "district_n"]).ngroups, 0),
        ("C 2017+", len(c), f"{c['year'].min()}-{c['year'].max()}", len(category_cols(c)), c["state_n"].nunique(),
         c.groupby(["state_n", "district_n"]).ngroups, 0),
    ], ("era", "rows", "years", "category cols", "states", "distinct units (all years)", "TOTAL rows")))
    lines += ["", f"GeoJSON: **{len(geo)}** administrative districts across {geo['state_n'].nunique()} states.", ""]

    # ---- units per year ---------------------------------------------------
    lines += ["## Reporting units per year", "",
              "Growth over time = new districts being created (splits), not new data coverage.", ""]
    per_year = [(int(y), int(n)) for y, n in a_units.groupby("Year")["unit_n"].nunique().items()]
    per_year.append((2016, int(b["district_n"].nunique())))
    per_year += [(int(y), int(n)) for y, n in c.groupby("year")["district_n"].nunique().items()]
    lines += [md_table(per_year, ("year", "units")), ""]

    # ---- unit of analysis -------------------------------------------------
    lines += ["## Unit of analysis", ""]
    rail_a = a_units[a_units["unit_n"].str.contains(r"rly|railway|grp", regex=True)]["unit_n"].nunique()
    lines.append(f"- Era A `DISTRICT` contains **{rail_a}** distinct railway / GRP police units, "
                 "so it is a police-unit column, not an administrative one.")
    for name, df in (("B 2016", b), ("C 2017+", c)):
        multi = df.groupby(["year", "state_n", "district_n"])["circle_n"].nunique()
        lines.append(f"- Era {name}: {int((multi > 1).sum())} district-years have more than one `registration_circles` "
                     f"row (max {int(multi.max())}); {df['district_n'].nunique()} distinct districts vs "
                     f"{df['circle_n'].nunique()} distinct circles.")
    zero_a = int((a_units["total"] == 0).sum())
    dup_a = int((a_units.groupby(["state_n", "unit_n", "Year"]).size() > 1).sum())
    lines.append(f"- Era A: **{zero_a}** unit-years with zero total (percent change undefined); "
                 f"**{dup_a}** duplicate (state, unit, year) keys.")
    lines.append("")

    # ---- name overlap -----------------------------------------------------
    lines += ["## Exact name overlap after normalisation", "",
              "How many units match *by exact string* once lower-cased and stripped of punctuation. "
              "Everything not matched here is the resolver workload.", ""]
    geo_keys = set(zip(geo["state_n"], geo["district_n"]))
    a_keys = set(zip(a_units["state_n"], a_units["unit_n"]))
    b_keys = set(zip(b["state_n"], b["district_n"]))
    a14 = a_units[a_units["Year"] == 2014]
    c22 = c[c["year"] == 2022]
    a_last = set(zip(a14["state_n"], a14["unit_n"]))
    c_last = set(zip(c22["state_n"], c22["district_n"]))
    lines += [md_table([
        ("Era A (all years) -> GeoJSON", coverage(a_keys, geo_keys)),
        ("Era A (2014 only) -> GeoJSON", coverage(a_last, geo_keys)),
        ("Era B 2016 -> GeoJSON", coverage(b_keys, geo_keys)),
        ("Era C (2022 only) -> GeoJSON", coverage(c_last, geo_keys)),
        ("GeoJSON covered by Era A (2014)", coverage(geo_keys, a_last)),
        ("GeoJSON covered by Era C (2022)", coverage(geo_keys, c_last)),
        ("Era A (2014) -> Era C (2022)", coverage(a_last, c_last)),
        ("Era C (2022) -> Era A (2014)", coverage(c_last, a_last)),
    ], ("join", "exact matches")), ""]

    # ---- states -----------------------------------------------------------
    lines += ["## State name sets", "",
              f"- Era A: {sorted(a_units['state_n'].unique())}",
              f"- Era C: {sorted(c['state_n'].unique())}",
              f"- GeoJSON: {sorted(geo['state_n'].unique())}", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwritten -> {OUT}")


if __name__ == "__main__":
    main()
